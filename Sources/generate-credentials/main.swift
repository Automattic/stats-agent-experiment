import Foundation

// `generate-credentials <json> <swift>` writes `CompiledCredentials`, the WordPress.com OAuth client from the JSON file,
// to the Swift file. The secret is written as its UTF-8 bytes in reverse order, so it doesn't appear as is in the
// binary. Without the JSON file, `CompiledCredentials` has no client. `CredentialsPlugin` runs it on every build.

struct Credentials: Decodable {
    let id: UInt64
    let secret: String

    private enum CodingKeys: String, CodingKey {
        case id = "client_id"
        case secret = "client_secret"
    }
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("Usage: generate-credentials <json> <swift>\n".utf8))
    exit(1)
}
let json = URL(filePath: arguments[1])
let swift = URL(filePath: arguments[2])

do {
    var id = "nil"
    var reversedSecret = "[]"
    if FileManager.default.fileExists(atPath: json.path(percentEncoded: false)) {
        let credentials = try JSONDecoder().decode(Credentials.self, from: Data(contentsOf: json))
        id = String(credentials.id)
        let bytes = credentials.secret.utf8.reversed().map { "0x" + String($0, radix: 16) }
        reversedSecret = "[\(bytes.joined(separator: ", "))]"
    }
    let source = """
        // Generated by generate-credentials from wp_com_credentials.json.
        enum CompiledCredentials {
            static let clientID: UInt64? = \(id)
            static let reversedSecret: [UInt8] = \(reversedSecret)
        }

        """
    try source.write(to: swift, atomically: true, encoding: .utf8)
} catch {
    FileHandle.standardError.write(Data("generate-credentials: \(error)\n".utf8))
    exit(1)
}
